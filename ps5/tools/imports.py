#!/usr/bin/env python3
"""LAS Recomp on the PS5 - the names the game code library may import, and the title's function for each.

    imports.py NM OUT.c OBJECT...

Run by the title's build (ps5/CMakeLists.txt) over the runtime's objects. The game code (ps5/tools/gamelib.py) calls
the runtime by name: rt_dispatch, rt_svc and the like from the generator, the rt_* hooks its patches call
(tools/patches.py), rando_word, fnprof_hit / g_fnprof; and a few of libc's, libm's and the compiler's functions. OUT.c
is the table runtime/platform/ps5_elf.c binds them with (ps5_gamelib_imports, sorted by name): every such name the
runtime defines, and the fixed list below.

SPDX-License-Identifier: MIT
"""
import os
import subprocess
import sys

PREFIXES = ('rt_', 'hle_', 'rando_', 'fnprof_', 'g_fnprof')

# What the code may call besides the runtime: the C library's (ps5/gamelib/include: memcpy and the like, the rounding
# mode, the libm functions clang leaves as calls) and compiler-rt's (128-bit arithmetic, half floats), the title's
# own copies of each. fegetround / fesetround are inline functions in the console's fenv.h: taking their address
# makes the title's copy.
LIBC = ['memcpy', 'memmove', 'memset', 'memcmp', 'strlen', 'fegetround', 'fesetround',
        'fabs', 'fabsf', 'sqrt', 'sqrtf', 'fma', 'fmaf', 'floor', 'floorf', 'ceil', 'ceilf', 'trunc', 'truncf',
        'round', 'roundf', 'rint', 'rintf', 'nearbyint', 'nearbyintf', 'fmin', 'fminf', 'fmax', 'fmaxf',
        'copysign', 'copysignf']
BUILTINS = ['__udivti3', '__umodti3', '__divti3', '__modti3', '__udivmodti4', '__muloti4', '__popcountdi2',
            '__popcountti2', '__clzti2', '__ctzti2', '__fixdfti', '__fixsfti', '__fixunsdfti', '__fixunssfti',
            '__floattidf', '__floattisf', '__floatuntidf', '__floatuntisf', '__truncsfhf2', '__truncdfhf2',
            '__extendhfsf2']


def main():
    nm, out, objects = sys.argv[1], sys.argv[2], sys.argv[3:]
    runtime = set()
    for o in objects:
        r = subprocess.run([nm, '--defined-only', '--extern-only', '--format=posix', o], capture_output=True, text=True)
        if r.returncode:
            sys.exit(f'imports.py: {nm} {o}: {r.stderr}')
        for line in r.stdout.splitlines():
            f = line.split()
            if len(f) >= 2 and f[1] in 'TDBRSC' and f[0].startswith(PREFIXES):
                runtime.add(f[0])
    names = {n: 'libc' for n in LIBC}
    names.update({n: 'builtin' for n in BUILTINS})
    names.update({n: 'runtime' for n in runtime})
    lines = ['// Generated by ps5/tools/imports.py from the runtime\'s objects: what the game code library may import',
             '// (runtime/platform/ps5_elf.h). Do not edit.',
             '#include <fenv.h>', '#include <math.h>', '#include <stddef.h>', '#include <string.h>', '',
             '#include "platform/ps5_elf.h"', '']
    for n in sorted(names):
        if names[n] != 'libc':
            lines.append(f'extern char {n};')  # (only its address is taken)
    lines += ['', 'const Ps5GameImport ps5_gamelib_imports[] = {']
    for n in sorted(names):  # (strcmp order: the loader's binary search)
        lines.append(f'    {{"{n}", (void *){n}}},' if names[n] == 'libc' else f'    {{"{n}", &{n}}},')
    lines += ['};', 'const size_t ps5_gamelib_import_count = sizeof ps5_gamelib_imports / sizeof *ps5_gamelib_imports;', '']
    with open(out + '.tmp', 'w') as f:
        f.write('\n'.join(lines))
    os.replace(out + '.tmp', out)
    print(f'imports.py: {len(runtime)} runtime names, {len(LIBC) + len(BUILTINS)} others')


if __name__ == '__main__':
    main()
